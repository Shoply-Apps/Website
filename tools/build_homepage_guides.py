# Writes the list of all guides into index.html (between the GUIDES-DATA markers),
# used by the homepage to rotate the "Free guide" line and the daily "From the blog" cards.
# Run after adding or renaming a guide: python3 tools/build_homepage_guides.py
import glob, html, json, os, re
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
LABEL = {  # short card label per guide (falls back to "Guide")
    'why-use-shopify': 'Shopify', 'essential-shopify-apps-new-store': 'Apps', 'shoply-item-scan-analytics': 'Our app',
    'shopify-store-launch-checklist': 'Launch', 'how-to-price-products': 'Pricing',
    'how-to-start-dropshipping-on-shopify': 'Dropshipping', 'dropshipping-profit-margins': 'Dropshipping',
    'how-to-find-winning-dropshipping-products': 'Dropshipping', 'dropshipping-vs-holding-inventory': 'Dropshipping',
    'increase-shopify-conversion-rate': 'Growth', 'shopify-seo-guide-for-beginners': 'SEO',
    'shopify-shipping-settings-guide': 'Shipping', 'free-shipping-threshold': 'Shipping',
    'reduce-cart-abandonment-shopify': 'Checkout', 'shopify-abandoned-cart-recovery': 'Checkout',
    'how-to-write-product-descriptions': 'Copywriting', 'shopify-product-photography': 'Photography',
    'shopify-product-image-size-guide': 'Images', 'shopify-email-marketing-guide': 'Email', 'welcome-email-series-ecommerce': 'Email',
    'social-media-marketing-for-shopify': 'Social media', 'sell-on-instagram-with-shopify': 'Instagram',
    'tiktok-marketing-for-shopify': 'TikTok', 'influencer-marketing-small-business': 'Influencers',
    'shopify-catalog-health-checklist': 'Checklist', 'shopify-inventory-management': 'Inventory',
    'shopify-products-selling-below-cost': 'Pricing & margin', 'shopify-out-of-stock-oversold': 'Stock',
    'shopify-product-page-seo-checklist': 'SEO', 'google-shopping-product-data-shopify': 'Google Shopping',
}
guides = []
for f in sorted(glob.glob('blog/*/index.html')):
    slug = f.split('/')[1]; s = open(f).read()
    h1 = html.unescape(re.search(r'<h1>(.*?)</h1>', s, re.S).group(1)).strip()
    short = re.sub(r'\s*[:(].*$', '', h1)  # "How to price your products: …" -> "How to price your products"
    desc = html.unescape(re.search(r'<meta name="description" content="(.*?)">', s).group(1))
    alt = html.unescape(re.search(r'class="post-hero"><img [^>]*alt="([^"]*)"', s).group(1))
    guides.append({'s': slug, 't': h1, 'h': short, 'l': LABEL.get(slug, 'Guide'), 'd': desc, 'a': alt})
data = json.dumps(guides, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/')
page = open('index.html').read()
block = f'<!-- GUIDES-DATA:start (generated by tools/build_homepage_guides.py) -->\n  <script type="application/json" id="guides-data">{data}</script>\n  <!-- GUIDES-DATA:end -->'
if 'GUIDES-DATA:start' in page:
    page = re.sub(r'<!-- GUIDES-DATA:start.*?GUIDES-DATA:end -->', lambda m: block, page, flags=re.S)
else:
    page = page.replace('</body>', '  ' + block + '\n</body>', 1)
page = re.sub(r'All \d+ guides →', f'All {len(guides)} guides →', page)
open('index.html', 'w').write(page)
print('guides', len(guides))
